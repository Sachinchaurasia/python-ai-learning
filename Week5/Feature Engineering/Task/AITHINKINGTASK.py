### **AI THINKING TASK – Answer**

# Creating better features can improve a model more than changing the algorithm because the quality of the input data has a direct impact on the quality of the predictions. Well-designed features capture meaningful relationships and patterns that help the model learn more effectively. Even a simple algorithm can perform very well when given informative features. Feature engineering also uses business knowledge to represent real-world problems more accurately. Therefore, improving the features often leads to better performance than simply switching to a more complex algorithm.

